/** The content of the Guide page: chapters made of paragraphs, steps, tips and screenshots.
 *  Screenshots live in public/guide/ and come from a demonstration installation. Text may use
 *  **bold** and `code`. Keep a chapter per menu entry, in the order of the menu. */

